<?php

namespace App\Console\Commands;

use App\Models\Team;
use App\Services\AsteriskDialplan;
use Illuminate\Console\Command;

class AsteriskContextsConfig extends Command
{
    protected $signature = 'asterisk:contexts-config';

    protected $description = 'Print the extensions.conf include declaring every tenant realtime context';

    /**
     * Asterisk only consults a realtime switch from a context declared in
     * extensions.conf. Write this output to e.g.
     * /etc/asterisk/extensions_tenants.conf, #include it from
     * extensions.conf and run "dialplan reload" after adding a team.
     */
    public function handle(AsteriskDialplan $dialplan): int
    {
        $this->line('; Generated by php artisan asterisk:contexts-config — do not edit.');

        $this->line('; Inbound DIDs (shared by every tenant): use it as the context of your provider trunk');
        $this->line($dialplan->inboundConfigStanza());

        $this->line('; Outside calls from the softphones (shared by every tenant)');
        $this->line($dialplan->outboundConfigStanza());

        $this->line('; Outbound campaigns (shared by every tenant)');
        $this->line($dialplan->campaignConfigStanza());

        $this->line('; Call recording subroutine (shared by every tenant)');
        $this->line($dialplan->recordingConfigStanza());

        Team::query()->orderBy('id')->each(function (Team $team) use ($dialplan) {
            $this->line("; {$team->name}");
            $this->line($dialplan->configStanza($team));
        });

        return self::SUCCESS;
    }
}
